#!/usr/bin/env bash
# Build of the k-vanio fork with nvcc only (the upstream removed the Makefile and
# the build hosts have no CMake). Output: build/rckangaroo plus the cubins, which
# the binary loads from the CWD (original mode) or from its own directory (-henry).
#
# Environment:
#   CUDA_HOME           CUDA toolkit (default /usr/local/cuda)
#   CUDA_INC_OVERRIDE   optional directory with a patched copy of the CUDA headers,
#                       searched before the toolkit's own. Needed with glibc >= 2.43
#                       + CUDA 13.1, whose crt/math_functions.h declares rsqrt/rsqrtf
#                       without noexcept(true) and clashes with bits/mathcalls.h.
#   CUDA_ARCHS          SASS targets for the CUDA kernels (KernelGen, KernelC and the
#                       fallback A/B), default "89 120". The turbo kernels come
#                       prebuilt in kernel_sm89.cubin / kernel_sm120.cubin.
#   OUT                 output directory (default ./build)
set -euo pipefail

cd "$(dirname "$0")"
CUDA_HOME="${CUDA_HOME:-/usr/local/cuda}"
NVCC="${NVCC:-$CUDA_HOME/bin/nvcc}"
OUT="${OUT:-build}"
CUDA_ARCHS="${CUDA_ARCHS:-89 120}"

INC=()
if [[ -n "${CUDA_INC_OVERRIDE:-}" ]]; then
	INC+=(-I"$CUDA_INC_OVERRIDE")
fi
GENCODE=()
for a in $CUDA_ARCHS; do
	GENCODE+=(-gencode "arch=compute_${a},code=sm_${a}")
done

mkdir -p "$OUT"
COMMON=(-O3 -std=c++17 "${INC[@]}" -I.)
CPP_SRCS=(RCKangaroo.cpp GpuKang.cpp Ec.cpp utils.cpp CallCubin.cpp Henry.cpp HenryStart.cpp)
OBJS=()
for src in "${CPP_SRCS[@]}"; do
	"$NVCC" "${COMMON[@]}" -Xcompiler -Wall,-Wno-unknown-pragmas -c "$src" -o "$OUT/${src%.cpp}.o"
	OBJS+=("$OUT/${src%.cpp}.o")
done
"$NVCC" "${COMMON[@]}" "${GENCODE[@]}" -c RCGpuCore.cu -o "$OUT/RCGpuCore.o"
OBJS+=("$OUT/RCGpuCore.o")
# explicit object list: a stale .o left in $OUT must never end up in the binary
"$NVCC" -o "$OUT/rckangaroo" "${OBJS[@]}" -lcuda -lpthread
cp kernel_sm89.cubin kernel_sm120.cubin "$OUT/"

# BUILDINFO: what was built, from which commit and with which compiler, so a
# deployed binary can be traced back (the worker image pins it in F4).
{
	echo "commit: $(git rev-parse HEAD 2>/dev/null || echo unknown)$(git diff --quiet HEAD 2>/dev/null || echo ' (dirty)')"
	echo "date: $(date -u +%Y-%m-%dT%H:%M:%SZ)"
	echo "cuda_archs: $CUDA_ARCHS"
	echo "cuda_inc_override: ${CUDA_INC_OVERRIDE:-none}"
	echo "nvcc:"
	"$NVCC" --version | sed 's/^/  /'
	echo "host compiler: $(${CXX:-g++} --version | head -1)"
	echo "sha256:"
	(cd "$OUT" && sha256sum rckangaroo kernel_sm89.cubin kernel_sm120.cubin | sed 's/^/  /')
} > "$OUT/BUILDINFO"
echo "built $OUT/rckangaroo"

# StartDistance C++ == Go (oracle 3 of F3): vectors generated by `kangdiff vectors`
"$OUT/rckangaroo" -henry-selftest henry_start_vectors.txt
